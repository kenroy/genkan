#!/usr/bin/env python3
"""Assemble main.js and styles.css from the sources in this repo.

main.template.js + src/icons.js + src/quotes.js + src/i18n.js + src/timetracker.js   -> main.js
src/base.css, scoped under .hp-root               -> styles.css
(plus plugin-only additions from styles.extra.css)
"""
import re, pathlib

here = pathlib.Path(__file__).parent
src = here / "src"
icons = (src / "icons.js").read_text().rstrip("\n")
quotes = (src / "quotes.js").read_text().rstrip("\n")
i18n = (src / "i18n.js").read_text().rstrip("\n")
timetracker = (src / "timetracker.js").read_text().rstrip("\n")
tpl = (here / "main.template.js").read_text()
main = tpl.replace("/*__ICONS__*/", icons).replace("/*__QUOTES__*/", quotes).replace("/*__I18N__*/", i18n).replace("/*__TIMETRACKER__*/", timetracker)
(here / "main.js").write_text(main)

# ---- CSS: scope everything under .hp-root ----
css = (src / "base.css").read_text()
css = re.sub(r"@import[^;]+;", "", css)
css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)

def split_top(s):
    """Yield (prelude, body) for each top-level block."""
    i, n = 0, len(s)
    while i < n:
        j = s.find("{", i)
        if j == -1: break
        prelude = s[i:j].strip()
        depth, k = 1, j + 1
        while depth:
            if s[k] == "{": depth += 1
            elif s[k] == "}": depth -= 1
            k += 1
        yield prelude, s[j+1:k-1]
        i = k

def scope_selector(sel):
    sel = sel.strip()
    if sel.startswith("#genkan-root"): return sel  # already scoped (higher specificity on purpose)
    if sel in (":root", "body", "html"): return ".hp-root"
    if sel.startswith("[data-theme"): return ".hp-root" + sel
    if sel.startswith(":root"): return ".hp-root" + sel[5:]
    if sel in ("*", "*::before", "*::after"): return ".hp-root " + sel
    return ".hp-root " + sel

def scope_rules(s):
    out = []
    for prelude, body in split_top(s):
        if prelude.startswith("@keyframes"):
            name = prelude.split()[1]
            out.append(f"{prelude.replace(name, 'hp-' + name)} {{{body}}}")
        elif prelude.startswith("@media"):
            if "prefers-color-scheme" in prelude:
                continue  # theme is driven by data-theme from Obsidian's own theme
            q = prelude[len("@media"):].strip()
            out.append(f"@container hp {q} {{\n{scope_rules(body)}\n}}")
        else:
            sels = ",\n".join(scope_selector(x) for x in prelude.split(","))
            out.append(f"{sels} {{{body}}}")
    return "\n".join(out)

scoped = scope_rules(css)
# keyframes were renamed — fix references
for name in set(re.findall(r"@keyframes hp-(\w+)", scoped)):
    scoped = re.sub(rf"(animation[^;]*?)\b{name}\b", rf"\1hp-{name}", scoped)
# Obsidian core styles `.empty-state` as a full-size overlay, which would sit on top of
# our buttons and swallow clicks — use our own class name for the same look
scoped = scoped.replace(".empty-state", ".hp-empty")
extra = (here / "styles.extra.css").read_text()
(here / "styles.css").write_text("/* GENERATED by build.py from src/base.css and styles.extra.css — edit those, not this file */\n" + scoped + "\n" + extra)
print("built main.js (%d lines) and styles.css (%d lines)" % (main.count("\n"), (scoped+extra).count("\n")))
